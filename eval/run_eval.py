"""Evaluation against the reference labels.

THE REFERENCE LABELS WERE GENERATED BY CLAUDE, not by a person (data/LABELING_PROVENANCE.md).
No metric is called "accuracy": every number is agreement with Claude-generated labels. If an
evaluated classifier is also the labeling model, its agreement is inflated by shared biases.

Subcommands (real data lives OUTSIDE the repo and is passed by path):
  estimate  --real DATASET --labels LABELS              token/cost estimate for the whole run
  smoke     --model M                                   5 synthetic rows, real API
  run       --model M --set {real,synthetic} [--real ... --labels ...] --out DIR
  stability --model M --real ... --labels ... --out DIR 30 real rows again, count class changes
  report    --out DIR                                    writes eval/results.md from metrics JSON
Private predictions go to DIR as *.local.jsonl (reply_NNNN + label only, never text).
"""
import argparse
import csv
import json
import math
import random
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from labels import LABELS  # noqa: E402

PRICING = json.loads((REPO / "config" / "pricing.json").read_text(encoding="utf-8"))
DEFAULT_METRICS = REPO / "eval" / "metrics"
MODELS = ("claude-opus-5-5", "claude-sonnet-5")
LABELER_ALIAS = "opus"        # the reference labels came from sub-agents requested as `opus`
SEED = 20260927
MAX_CALLS = 1000              # stop condition (whole order)
MAX_COST_USD = 10.0           # stop condition (whole order, estimated)
MAX_FAILURE_RATE = 0.05       # stop condition
COUNTER = REPO / "eval" / "calls.local.json"   # running call/cost tally across subcommands

# Cost of an error, gold -> predicted (DECISION.md explains each). Correct = 0, other errors = 1.
EXPENSIVE = {
    ("quiere_contacto", "sin_intencion"): 5,   # a person who asked to be called is ignored
    ("quiere_contacto", "pospone"): 5,
    ("quiere_contacto", "no_interesado"): 5,
    ("prefiere_escrito", "quiere_contacto"): 3,   # we call someone who refused calls
    ("pide_informacion", "sin_intencion"): 3,     # a question goes unanswered
}
OPT_OUT_MISSED = 5   # an explicit opt-out classified as anything but no_interesado


# ---------------------------------------------------------------- metrics

def confusion(gold, pred, labels=LABELS):
    """matrix[g][p] = how many times true class g was predicted as p."""
    if len(gold) != len(pred):
        raise ValueError("gold and pred differ in length")
    unknown = (set(gold) | set(pred)) - set(labels)
    if unknown:
        raise ValueError(f"classes outside the guide: {sorted(unknown)}")
    m = {g: dict.fromkeys(labels, 0) for g in labels}
    for g, p in zip(gold, pred):
        m[g][p] += 1
    return m


def per_class(gold, pred, labels=LABELS):
    """{class: (precision, recall, support)}. None when the denominator is 0 (no data)."""
    m = confusion(gold, pred, labels)
    out = {}
    for c in labels:
        tp = m[c][c]
        predicted = sum(m[g][c] for g in labels)
        support = sum(m[c].values())
        out[c] = (tp / predicted if predicted else None, tp / support if support else None, support)
    return out


def agreement(gold, pred):
    """Share of rows where pred equals the Claude-generated reference label."""
    return sum(g == p for g, p in zip(gold, pred)) / len(gold) if gold else None


def macro_f1(gold, pred, labels=LABELS):
    """Mean F1 over classes present in gold (a class with no support is skipped, not zero)."""
    f1s = []
    for c, (p, r, n) in per_class(gold, pred, labels).items():
        if n == 0:
            continue
        p, r = p or 0.0, r or 0.0
        f1s.append(2 * p * r / (p + r) if p + r else 0.0)
    return sum(f1s) / len(f1s) if f1s else None


def bootstrap_ci(gold, pred, metric, n=1000, seed=SEED, alpha=0.05):
    """Percentile bootstrap CI for metric(gold, pred), fixed seed."""
    rng = random.Random(seed)
    idx = range(len(gold))
    vals = []
    for _ in range(n):
        s = [rng.choice(idx) for _ in idx]
        v = metric([gold[i] for i in s], [pred[i] for i in s])
        if v is not None:
            vals.append(v)
    vals.sort()
    lo = vals[int(alpha / 2 * len(vals))]
    hi = vals[min(len(vals) - 1, int((1 - alpha / 2) * len(vals)))]
    return lo, hi


def error_cost(gold, pred, gold_opt=None):
    """Mean cost per row using EXPENSIVE; missed explicit opt-outs cost OPT_OUT_MISSED."""
    total, expensive = 0, 0
    for i, (g, p) in enumerate(zip(gold, pred)):
        if gold_opt and gold_opt[i] and p != "no_interesado":
            c = OPT_OUT_MISSED
        elif g == p:
            c = 0
        else:
            c = EXPENSIVE.get((g, p), 1)
        total += c
        expensive += c > 1
    return {"mean_cost": total / len(gold) if gold else None, "expensive_errors": expensive}


def percentile(xs, q):
    xs = sorted(xs)
    if not xs:
        return None
    k = (len(xs) - 1) * q
    f, c = math.floor(k), math.ceil(k)
    return xs[f] if f == c else xs[f] + (xs[c] - xs[f]) * (k - f)


def call_cost(model, log):
    p = PRICING["models"][model]
    return (log["input_tokens"] * p["input"] + log["cache_creation_input_tokens"] * p["cache_write_5m"]
            + log["cache_read_input_tokens"] * p["cache_read"] + log["output_tokens"] * p["output"]) / 1e6


def report(gold, pred, labels=LABELS):
    lines = [f"agreement with Claude-generated labels {agreement(gold, pred):.3f} over {len(gold)} rows",
             f"{'class (vs Claude labels)':<26}{'precision':>10}{'recall':>8}{'n':>5}"]
    fmt = lambda x: "  -  " if x is None else f"{x:.2f}"
    for c, (p, r, n) in per_class(gold, pred, labels).items():
        lines.append(f"{c:<26}{fmt(p):>10}{fmt(r):>8}{n:>5}")
    lines.append("Claude-label distribution: " + str(dict(Counter(gold))))
    return "\n".join(lines)


def summarize(name, rows, preds, logs=None, model=None):
    """Aggregates only (safe to publish): metrics, CIs, per-class, confusion, subsets, cost."""
    gold = [r["gold"] for r in rows]
    pred = [p["label"] for p in preds]
    gold_opt = [r.get("gold_opt", False) for r in rows]
    out = {
        "name": name, "n": len(rows),
        "agreement": agreement(gold, pred), "agreement_ci95": bootstrap_ci(gold, pred, agreement),
        "macro_f1": macro_f1(gold, pred), "macro_f1_ci95": bootstrap_ci(gold, pred, macro_f1),
        "per_class": per_class(gold, pred), "confusion": confusion(gold, pred),
        "error_cost": error_cost(gold, pred, gold_opt),
        "disagreements": [r["id"] for r, p in zip(rows, pred) if r["gold"] != p],
    }
    for key in ("hard_v1", "hard_v2"):
        sel = [i for i, r in enumerate(rows) if r.get(key)]
        if sel:
            g, p = [gold[i] for i in sel], [pred[i] for i in sel]
            out[key] = {"n": len(sel), "agreement": agreement(g, p), "agree_rows": sum(a == b for a, b in zip(g, p))}
    if logs:
        lat = [l["latency_s"] for l in logs]
        cost = sum(call_cost(model, l) for l in logs)
        out.update({
            "latency_p50_s": percentile(lat, 0.5), "latency_p95_s": percentile(lat, 0.95),
            "cost_usd": cost, "cost_per_1000_usd": cost / len(logs) * 1000,
            "format_errors": sum(l["format_errors"] for l in logs),
            "tokens": {k: sum(l[k] for l in logs) for k in
                       ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens")},
        })
    return out


# ---------------------------------------------------------------- data

def load_real(dataset_path, labels_path):
    """Labelable rows: reply + last outbound (pseudonymized) + reference label (v2) + hard subsets."""
    with open(labels_path, encoding="utf-8") as f:
        lab = {r["reply_id"]: r for r in csv.DictReader(f)}
    rows = []
    with open(dataset_path, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["filtro"]:
                continue
            L = lab[r["reply_id"]]
            rows.append({
                "id": r["reply_id"], "reply": r["reply_text_scrubbed"], "outbound": r["mensaje_saliente"],
                "gold": L["etiqueta_final"], "gold_opt": L["baja_explicita_final"] == "si",
                "hard_v2": L["confianza_final"] == "baja" or L["desacuerdo"] == "si",
                "hard_v1": L.get("confianza_final_v1") == "baja" or L.get("desacuerdo_v1") == "si",
            })
    return rows


def load_synthetic():
    from data import synthetic
    return [{"id": x["id"], "reply": x["reply_text"], "outbound": x["outbound_text"], "gold": x["label"],
             "gold_opt": x["explicit_opt_out"], "hard_v1": False, "hard_v2": False} for x in synthetic.rows()]


# ---------------------------------------------------------------- running

def _tally():
    return json.loads(COUNTER.read_text(encoding="utf-8")) if COUNTER.exists() else {"calls": 0, "cost_usd": 0.0}


def _save_tally(t):
    COUNTER.write_text(json.dumps(t), encoding="utf-8")


def classify_rows(rows, model, client=None, workers=4):
    """Classify rows; enforces the call ceiling and the failure-rate stop. Returns (preds, logs)."""
    if model == "rules":
        from baseline import rules
        return [{"id": r["id"], "label": rules.classify(r["reply"], r["outbound"]).label} for r in rows], None
    from concurrent.futures import ThreadPoolExecutor
    from dataclasses import asdict
    from classifier import llm
    tally = _tally()
    if tally["calls"] + len(rows) > MAX_CALLS:
        raise SystemExit(f"STOP: {tally['calls']} + {len(rows)} calls would exceed {MAX_CALLS}")
    results = {}

    def one(r):
        try:
            pred, log = llm.classify_with_log(r["reply"], r["outbound"], model=model, client=client)
            return r["id"], pred.label, asdict(log), None
        except Exception as e:   # counted as a failed call; the run stops if >5 % fail
            return r["id"], None, None, f"{type(e).__name__}: {e}"

    failures = 0
    with ThreadPoolExecutor(max_workers=workers) as ex:
        for rid, label, log, err in ex.map(one, rows):
            tally["calls"] += 1
            if err:
                failures += 1
            else:
                tally["cost_usd"] += call_cost(model, log)
            results[rid] = (label, log, err)
            done = len(results)
            if done >= 20 and failures / done > MAX_FAILURE_RATE:
                _save_tally(tally)
                raise SystemExit(f"STOP: {failures}/{done} calls failed (> {MAX_FAILURE_RATE:.0%}). Last: {err}")
    _save_tally(tally)
    if failures / len(rows) > MAX_FAILURE_RATE:
        raise SystemExit(f"STOP: {failures}/{len(rows)} calls failed")
    preds = [{"id": r["id"], "label": results[r["id"]][0] or "sin_intencion", "failed": results[r["id"]][2] is not None}
             for r in rows]
    logs = [results[r["id"]][1] for r in rows if results[r["id"]][1]]
    return preds, logs


def estimate(rows_real, rows_syn, system_chars):
    """Conservative estimate for the whole order (both models)."""
    sys_tok = int(system_chars / 3.0)                  # Spanish text, newer tokenizer: ~3 chars/token
    user_tok = 200
    out_tok = 800                                      # low-effort thinking + JSON, generous
    per_model = 5 + len(rows_real) + len(rows_syn) + 30
    total = {}
    for m in MODELS:
        p = PRICING["models"][m]
        writes = max(1, int(per_model * 0.10))         # assume 10 % cache misses
        reads = per_model - writes
        cost = (writes * sys_tok * p["cache_write_5m"] + reads * sys_tok * p["cache_read"]
                + per_model * user_tok * p["input"] + per_model * out_tok * p["output"]) / 1e6
        total[m] = {"calls": per_model, "cost_usd": round(cost, 2)}
    return {"system_prompt_tokens_est": sys_tok, "per_model": total,
            "calls": sum(v["calls"] for v in total.values()),
            "cost_usd": round(sum(v["cost_usd"] for v in total.values()), 2)}


def _client():
    import anthropic
    return anthropic.Anthropic(max_retries=3, timeout=120.0)


def _write_private(out_dir, name, preds, logs):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    with open(out / f"{name}.local.jsonl", "w", encoding="utf-8") as f:
        for i, p in enumerate(preds):
            f.write(json.dumps({**p, "log": logs[i] if logs and i < len(logs) else None}) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["estimate", "smoke", "run", "stability", "report", "from-subagents", "from-labeling"])
    ap.add_argument("--model", choices=("rules",) + MODELS)
    ap.add_argument("--set", choices=["real", "synthetic"])
    ap.add_argument("--real")
    ap.add_argument("--labels")
    ap.add_argument("--out", default=str(DEFAULT_METRICS),
                    help="where metrics, private logs and (for report, if not the default) results.md are written")
    ap.add_argument("--dir", help="directory with sub-agent outputs (outside the repo)")
    ap.add_argument("--agent", choices=["haiku", "sonnet"])
    ap.add_argument("--passes", nargs=2, help="v2 pass A and pass B label files (outside the repo)")
    a = ap.parse_args(argv)
    metrics_dir = Path(a.out)
    metrics_dir.mkdir(parents=True, exist_ok=True)

    if a.cmd == "estimate":
        from classifier import llm
        e = estimate(load_real(a.real, a.labels), load_synthetic(), len(llm.SYSTEM_PROMPT))
        print(json.dumps(e, indent=2))
        if e["cost_usd"] > MAX_COST_USD or e["calls"] > MAX_CALLS:
            raise SystemExit("STOP: estimate exceeds the cost or call ceiling")
        return
    if a.cmd == "smoke":
        rows = load_synthetic()[:5]
        preds, logs = classify_rows(rows, a.model, _client())
        print(json.dumps({"model": a.model, "ok": sum(not p["failed"] for p in preds), "n": len(rows),
                          "agree": sum(p["label"] == r["gold"] for p, r in zip(preds, rows)),
                          "cost_usd": round(sum(call_cost(a.model, l) for l in logs), 4),
                          "cache_read_tokens": sum(l["cache_read_input_tokens"] for l in logs)}))
        return
    if a.cmd in ("run", "stability"):
        rows = load_real(a.real, a.labels) if (a.cmd == "stability" or a.set == "real") else load_synthetic()
        if a.cmd == "stability":
            rows = random.Random(SEED).sample(rows, 30)
        client = None if a.model == "rules" else _client()
        preds, logs = classify_rows(rows, a.model, client)
        name = f"{a.cmd}-{a.model}-{a.set or 'real'}"
        if a.model != "rules":
            _write_private(a.out, name, preds, logs)
        if a.cmd == "run":
            s = summarize(name, rows, preds, logs, a.model if logs else None)
            s["failed_calls"] = sum(p.get("failed", False) for p in preds)
            (metrics_dir / f"{name}.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
            print(report([r["gold"] for r in rows], [p["label"] for p in preds]))
        else:
            first = {}
            prev = Path(a.out) / f"run-{a.model}-real.local.jsonl"
            for line in prev.read_text(encoding="utf-8").splitlines():
                d = json.loads(line)
                first[d["id"]] = d["label"]
            changed = [p["id"] for p in preds if first.get(p["id"]) != p["label"]]
            s = {"name": name, "n": len(preds), "changed": len(changed), "changed_ids": changed}
            (metrics_dir / f"{name}.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
            print(json.dumps(s))
        return
    if a.cmd == "from-subagents":
        # Claude Code sub-agents with a pinned model (method approved 2026-09-27): no cost or
        # latency is measured; the outputs are validated exactly like llm.parse_answer.
        from eval.subagent_batch import validate
        plan = json.loads((Path(a.dir) / "plan.local.json").read_text(encoding="utf-8"))
        got = {}
        for key, ids in plan.items():
            f = Path(a.dir) / f"{a.agent}-{key}.local.jsonl"
            if isinstance(ids, list) and f.exists():
                for line in f.read_text(encoding="utf-8").splitlines():
                    if line.strip():
                        d = validate(line)
                        got.setdefault(key[0], {})[d["id"]] = d["label"]
        real = load_real(a.real, a.labels)
        for set_name, key, rows in (("real", "R", real), ("synthetic", "S", load_synthetic())):
            if key in got:
                missing = [r["id"] for r in rows if r["id"] not in got[key]]
                if missing:
                    raise SystemExit(f"STOP: {len(missing)} rows without a valid answer in {set_name}: {missing[:5]}")
                preds = [{"id": r["id"], "label": got[key][r["id"]]} for r in rows]
                s = summarize(f"run-subagent-{a.agent}-{set_name}", rows, preds)
                s["method"] = "Claude Code sub-agent, pinned model alias; batches of <= 20; no cost/latency measured"
                (metrics_dir / f"run-subagent-{a.agent}-{set_name}.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
                print(set_name, round(s["agreement"], 3), round(s["macro_f1"], 3), s["error_cost"])
        if "E" in got and "R" in got:
            changed = sorted(i for i, lab in got["E"].items() if got["R"].get(i) != lab)
            s = {"name": f"stability-subagent-{a.agent}-real", "n": len(got["E"]), "changed": len(changed), "changed_ids": changed}
            (metrics_dir / f"stability-subagent-{a.agent}-real.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
            print("stability", s["changed"], "/", s["n"])
        return
    if a.cmd == "from-labeling":
        # e1: the v2 labeling passes A and B are already classifications by the labeling model
        # (confirmed claude-opus-5-5 for pass A) with the same guide. Zero new calls. Not independent.
        real = load_real(a.real, a.labels)
        for tag, path in zip(("a", "b"), a.passes):
            with open(path, encoding="utf-8") as f:
                lab = {r["reply_id"]: r["etiqueta"] for r in csv.DictReader(f)}
            preds = [{"id": r["id"], "label": lab[r["id"]]} for r in real]
            s = summarize(f"run-labeler-pass-{tag}-real", real, preds)
            s["method"] = f"v2 labeling pass {tag.upper()} vs the reconciled reference label (self-consistency, not independent)"
            (metrics_dir / f"run-labeler-pass-{tag}-real.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
            print(tag, round(s["agreement"], 3), round(s["macro_f1"], 3))
        return
    if a.cmd == "report":
        from eval import results_md
        default = metrics_dir.resolve() == DEFAULT_METRICS.resolve()
        results_md.write(metrics_dir, REPO / "eval" / "results.md" if default else metrics_dir / "results.md")


if __name__ == "__main__":
    main()
